SELECT '用户' AS 表, COUNT(*) AS 行数 FROM `user`
UNION ALL SELECT '分类',   COUNT(*) FROM `category`
UNION ALL SELECT '物品',   COUNT(*) FROM `item`
UNION ALL SELECT '可租时段', COUNT(*) FROM `item_available_period`
UNION ALL SELECT '订单',   COUNT(*) FROM `orders`
UNION ALL SELECT '评价',   COUNT(*) FROM `review`
UNION ALL SELECT '收藏',   COUNT(*) FROM `favorite`
UNION ALL SELECT '钱包流水', COUNT(*) FROM `wallet_transaction`;

SELECT `status` AS 订单状态, COUNT(*) AS 数量 FROM `orders` GROUP BY `status` ORDER BY `status`;
